import {mkdir, readFile, writeFile} from "node:fs/promises";
import path from "node:path";

const script = await readFile("src/template.js", "utf8");
const outlineCleanupScript = await readFile("src/outline-cleanup.js", "utf8");
const basicStyling = await readFile("templates/basic/styling.css", "utf8");
const outlineStartMarker = "/* shared-markdown-outline:start */";
const outlineEndMarker = "/* shared-markdown-outline:end */";
const outlineStart = basicStyling.indexOf(outlineStartMarker);
const outlineEnd = basicStyling.indexOf(outlineEndMarker, outlineStart);
if (outlineStart === -1 || outlineEnd === -1) {
  throw new Error("Shared Markdown outline styles are missing their markers");
}
const sharedOutlineStyling = basicStyling.slice(
  outlineStart,
  outlineEnd + outlineEndMarker.length,
);
const templates = [
  {
    sourceDir: "templates/basic",
    outputDir: "dist",
    cards: [{directory: "", runtimeSides: ["front", "back"]}],
  },
  {
    sourceDir: "templates/basic",
    outputDir: "dist/basic",
    cards: [{directory: "", runtimeSides: ["front", "back"]}],
  },
  {
    sourceDir: "templates/english-vocabulary",
    outputDir: "dist/english-vocabulary",
    additionalStyling: sharedOutlineStyling,
    cards: [
      {
        directory: "recite",
        outlineCleanupSides: ["front"],
        runtimeSides: ["back"],
      },
      {
        directory: "spelling",
        outlineCleanupSides: ["front"],
        runtimeSides: ["back"],
      },
      {
        directory: "dictation",
        outlineCleanupSides: ["front"],
        runtimeSides: ["back"],
      },
    ],
  },
];

async function buildTemplate({sourceDir, outputDir, cards, additionalStyling = ""}) {
  const styling = await readFile(path.join(sourceDir, "styling.css"), "utf8");
  const generatedHeader = (directory) =>
    `<!-- Generated from ${path.join(sourceDir, directory)}/. Do not edit this file directly. -->`;
  const withRuntime = (template) =>
    `${template.header}\n${template.content.trim()}\n\n<script>\n${script.trim()}\n</script>\n`;
  const withOutlineCleanup = (template) =>
    `${template.header}\n${template.content.trim()}\n\n<script>\n${outlineCleanupScript.trim()}\n</script>\n`;
  const generated = (template) =>
    `${template.header}\n${template.content.trim()}\n`;

  await mkdir(outputDir, {recursive: true});
  await writeFile(
    path.join(outputDir, "styling.css"),
    `${styling.trim()}${additionalStyling ? `\n\n${additionalStyling.trim()}` : ""}\n`,
    "utf8",
  );

  await Promise.all(
    cards.map(async ({directory, outlineCleanupSides = [], runtimeSides}) => {
      const sourceCardDir = path.join(sourceDir, directory);
      const outputCardDir = path.join(outputDir, directory);
      const [front, back] = await Promise.all([
        readFile(path.join(sourceCardDir, "front.html"), "utf8"),
        readFile(path.join(sourceCardDir, "back.html"), "utf8"),
      ]);
      const header = generatedHeader(directory);
      await mkdir(outputCardDir, {recursive: true});
      await Promise.all([
        writeFile(
          path.join(outputCardDir, "front.html"),
          (runtimeSides.includes("front")
            ? withRuntime
            : outlineCleanupSides.includes("front")
              ? withOutlineCleanup
              : generated)({
            header,
            content: front,
          }),
          "utf8",
        ),
        writeFile(
          path.join(outputCardDir, "back.html"),
          (runtimeSides.includes("back")
            ? withRuntime
            : outlineCleanupSides.includes("back")
              ? withOutlineCleanup
              : generated)({
            header,
            content: back,
          }),
          "utf8",
        ),
      ]);
    }),
  );
}

await Promise.all(templates.map(buildTemplate));
